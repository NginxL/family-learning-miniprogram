'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const { knowledge, resources } = require('./knowledge');
for (const [name, value] of [['knowledge-data.json', knowledge()], ['resources.json', resources]]) {
  const serialized = JSON.stringify(value);
  for (const folder of ['shared', 'cloudfunctions/familyApi/learning']) {
    fs.mkdirSync(path.join(root, folder), { recursive: true });
    fs.writeFileSync(path.join(root, folder, name), serialized + '\n');
  }
  // The native mini-program loader registers JS modules; it has no Node JSON loader.
  const clientFolder = path.join(root, 'miniprogram/lib/learning');
  fs.mkdirSync(clientFolder, { recursive: true });
  fs.writeFileSync(path.join(clientFolder, name.replace(/\.json$/, '.js')),
    '// Generated by scripts/sync-shared.js. Run npm run build after editing source data.\nmodule.exports = ' + serialized + ';\n');
  fs.rmSync(path.join(clientFolder, name), { force: true });
}
for (const name of ['catalog.js', 'learning.js', 'child-profile.js']) {
  const source = '// Generated from shared/' + name + '. Run npm run build after editing the source.\n' + fs.readFileSync(path.join(root, 'shared', name), 'utf8');
  for (const folder of ['miniprogram/lib/learning', 'cloudfunctions/familyApi/learning']) {
    fs.mkdirSync(path.join(root, folder), { recursive: true });
    fs.writeFileSync(path.join(root, folder, name), source);
  }
}
console.log('Knowledge, source records and learning rules copied to both deployable packages.');
