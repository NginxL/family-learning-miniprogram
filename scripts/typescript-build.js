'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const { knowledge, resources } = require('./knowledge');

// Build and check share one map; checked-in JS is never a second source of truth.
function artifacts() {
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'family-learning-ts-'));
  try {
    execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', path.join(root, 'tsconfig.build.json'), '--outDir', output, '--pretty', 'false'], { cwd: root, stdio: 'pipe' });
    const { assertKnowledge } = require(path.join(output, 'shared/knowledge-validation.js'));
    const items = knowledge();
    assertKnowledge(items);
    const files = new Map();
    for (const [name, value] of [['knowledge-data.json', items], ['resources.json', resources]]) {
      const serialized = JSON.stringify(value);
      for (const folder of ['shared', 'cloudfunctions/familyApi/learning']) files.set(`${folder}/${name}`, serialized + '\n');
      files.set(`miniprogram/lib/learning/${name.replace(/\.json$/, '.js')}`,
        '// Generated by scripts/sync-shared.js. Run npm run build after editing source data.\nmodule.exports = ' + serialized + ';\n');
    }
    const add = (source, targets) => {
      const generated = `// Generated from src/${source.replace(/\.js$/, '.ts')}. Run npm run build; do not edit this file.\n`
        + fs.readFileSync(path.join(output, source), 'utf8');
      for (const target of targets) files.set(target, generated);
    };
    for (const name of ['catalog', 'learning', 'child-profile']) add(`shared/${name}.js`,
      [`shared/${name}.js`, `miniprogram/lib/learning/${name}.js`, `cloudfunctions/familyApi/learning/${name}.js`]);
    for (const name of ['index', 'service', 'store']) add(`cloud/${name}.js`, [`cloudfunctions/familyApi/${name}.js`]);
    add('client/cloud-transport.js', ['miniprogram/lib/cloud-transport.js']);
    return files;
  } catch (error) {
    if (error.stdout) process.stderr.write(error.stdout);
    throw error;
  } finally {
    fs.rmSync(output, { recursive: true, force: true });
  }
}
module.exports = { artifacts };
