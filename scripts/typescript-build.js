'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const { knowledge, resourcesFor } = require('./knowledge');
const lowerPrimary = require('./lower-primary');
const recitationPages = require('../data/catalogs/chinese-recitation-page-evidence.json').pages;
const { dataModule } = require('./data-module');

// Build and check share one map; checked-in JS is never a second source of truth.
function artifacts() {
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'family-learning-ts-'));
  try {
    execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', path.join(root, 'tsconfig.build.json'), '--outDir', output, '--pretty', 'false'], { cwd: root, stdio: 'pipe' });
    const { assertKnowledge } = require(path.join(output, 'shared/knowledge-validation.js'));
    const items = knowledge();
    assertKnowledge(items, recitationPages);
    // Count the final catalogue, including legacy starter entries, using the same compiled code as clients.
    fs.writeFileSync(path.join(output, 'shared/knowledge-data.json'), JSON.stringify(items));
    const resources = resourcesFor(require(path.join(output, 'shared/catalog.js')));
    const files = new Map();
    files.set('miniprogram/lib/word-dictionary-data.js', '// Generated from sourced dictionary supplements. Run npm run build.\n'
      + dataModule(require('./word-dictionary').wordDictionaryData(require(path.join(output, 'shared/catalog.js')))));
    files.set('miniprogram/lib/lower-primary-pinyin.js', '// Generated from the verified lower-primary catalogue. Run npm run build.\n'
      + dataModule({ ...lowerPrimary.pinyin(), ...lowerPrimary.data.extraPinyin,
        ...require('../data/catalogs/chinese-foundation-pinyin.json') }));
    for (const [name, value] of [['knowledge-data.json', items], ['resources.json', resources]]) {
      const serialized = JSON.stringify(value);
      for (const folder of ['shared', 'cloudfunctions/familyApi/learning']) files.set(`${folder}/${name}`, serialized + '\n');
      files.set(`miniprogram/lib/learning/${name.replace(/\.json$/, '.js')}`,
        '// Generated by scripts/sync-shared.js. Run npm run build after editing source data.\n' + dataModule(value));
    }
    const add = (source, targets) => {
      const generated = `// Generated from src/${source.replace(/\.js$/, '.ts')}. Run npm run build; do not edit this file.\n`
        + fs.readFileSync(path.join(output, source), 'utf8');
      for (const target of targets) files.set(target, generated);
    };
    for (const name of ['catalog', 'reading-catalog', 'learning', 'child-profile', 'narration', 'speech-profile']) add(`shared/${name}.js`,
      [`shared/${name}.js`, `miniprogram/lib/learning/${name}.js`, `cloudfunctions/familyApi/learning/${name}.js`]);
    for (const name of ['index', 'service', 'store', 'validation', 'homework', 'speech', 'speech-provider', 'persistent-speech', 'speech-index']) add(`cloud/${name}.js`, [`cloudfunctions/familyApi/${name}.js`]);
    add('client/cloud-transport.js', ['miniprogram/lib/cloud-transport.js']);
    add('miniprogram/app.js', ['miniprogram/app.js']);
    for (const name of ['sync-engine', 'task-groups', 'page', 'errors', 'task-route', 'homework-media', 'pinyin', 'pinyin-data', 'study-notes-view', 'content-detail', 'planned-task-edit', 'content-schedule', 'content-presentation', 'learning-navigation', 'word-entry'])
      add(`miniprogram/lib/${name}.js`, [`miniprogram/lib/${name}.js`]);
    add('miniprogram/components/learning-card/index.js', ['miniprogram/components/learning-card/index.js']);
    add('miniprogram/lib/speech-player.js', ['miniprogram/lib/speech-player.js']);
    add('miniprogram/lib/speech-cache.js', ['miniprogram/lib/speech-cache.js']);
    add('miniprogram/components/speech-button/index.js', ['miniprogram/components/speech-button/index.js']);
    const pages = JSON.parse(fs.readFileSync(path.join(root, 'miniprogram/app.json'), 'utf8')).pages;
    for (const page of pages) add(`miniprogram/${page}.js`, [`miniprogram/${page}.js`]);
    return files;
  } catch (error) {
    if (error.stdout) process.stderr.write(error.stdout);
    throw error;
  } finally {
    fs.rmSync(output, { recursive: true, force: true });
  }
}
module.exports = { artifacts };
